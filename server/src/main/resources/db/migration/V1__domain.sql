-- Estudiantes
CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    date_birth DATE,
    biography TEXT
);

-- Intereses
CREATE TABLE interests (
    id_interest BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE students_interests (
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
    student_id BIGINT,
    interest_id BIGINT,
    PRIMARY KEY (student_id, interest_id),
    FOREIGN KEY (student_id) REFERENCES students(id),
    FOREIGN KEY (interest_id) REFERENCES interests(id_interest)
);

-- Comentarios
CREATE TABLE comments (
    comment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL,
    author_id BIGINT NOT NULL,
    date DATE NOT NULL,
    FOREIGN KEY (author_id) REFERENCES students(id)
);

-- Contenidos
CREATE TABLE contents (
    content_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    information TEXT NOT NULL,
    author_id BIGINT NOT NULL,
    like_count INTEGER DEFAULT 0,
    date DATE NOT NULL,
    FOREIGN KEY (author_id) REFERENCES students(id)
);

-- Temas de un contenido (muchos-a-muchos)
CREATE TABLE content_topics (
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content_id INTEGER,
    interest_id BIGINT,
    PRIMARY KEY (content_id, interest_id),
    FOREIGN KEY (content_id) REFERENCES contents(content_id),
    FOREIGN KEY (interest_id) REFERENCES interests(id_interest)
);

-- Likes de estudiantes a contenidos
CREATE TABLE content_likes (
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
    content_id INTEGER,
    student_id BIGINT,
    PRIMARY KEY (content_id, student_id),
    FOREIGN KEY (content_id) REFERENCES contents(content_id),
    FOREIGN KEY (student_id) REFERENCES students(id)
);

-- Comentarios en contenido
CREATE TABLE content_comments (
    content_id INTEGER,
    comment_id INTEGER,
    PRIMARY KEY (content_id, comment_id),
    FOREIGN KEY (content_id) REFERENCES contents(content_id),
    FOREIGN KEY (comment_id) REFERENCES comments(comment_id)
);

-- Pedidos de ayuda
CREATE TABLE help_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    information TEXT NOT NULL,
    urgency TEXT NOT NULL,
    student_id BIGINT NOT NULL,
    is_completed BOOLEAN NOT NULL,
    request_date DATE NOT NULL,
    FOREIGN KEY (student_id) REFERENCES students(id)
);

-- Temas de los pedidos
CREATE TABLE help_request_topics (
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
    request_id INTEGER,
    interest_id BIGINT,
    PRIMARY KEY (request_id, interest_id),
    FOREIGN KEY (request_id) REFERENCES help_requests(request_id),
    FOREIGN KEY (interest_id) REFERENCES interests(id_interest)
);

-- Comentarios en pedidos
CREATE TABLE help_request_comments (
    request_id INTEGER,
    comment_id INTEGER,
    PRIMARY KEY (request_id, comment_id),
    FOREIGN KEY (request_id) REFERENCES help_requests(request_id),
    FOREIGN KEY (comment_id) REFERENCES comments(comment_id)
);

-- Grupos de estudio
CREATE TABLE study_groups (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    topic_id BIGINT,
    date DATE NOT NULL,
    hidden BOOLEAN NOT NULL,
    FOREIGN KEY (topic_id) REFERENCES interests(id_interest)
);

-- Miembros del grupo
CREATE TABLE study_group_members (
    group_id BIGINT,
    student_id BIGINT,
    PRIMARY KEY (group_id, student_id),
    FOREIGN KEY (group_id) REFERENCES study_groups(group_id),
    FOREIGN KEY (student_id) REFERENCES students(id)
);

-- Contenidos asociados al grupo
CREATE TABLE study_group_contents (
    group_id BIGINT,
    content_id INTEGER,
    PRIMARY KEY (group_id, content_id),
    FOREIGN KEY (group_id) REFERENCES study_groups(group_id),
    FOREIGN KEY (content_id) REFERENCES contents(content_id)
);

-- Ayudas asociadas al grupo
CREATE TABLE study_group_help_requests (
    group_id BIGINT,
    request_id INTEGER,
    PRIMARY KEY (group_id, request_id),
    FOREIGN KEY (group_id) REFERENCES study_groups(group_id),
    FOREIGN KEY (request_id) REFERENCES help_requests(request_id)
);

-- Chats entre estudiantes
CREATE TABLE chats (
    chat_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_a_id BIGINT NOT NULL,
    student_b_id BIGINT NOT NULL,
    FOREIGN KEY (student_a_id) REFERENCES students(id),
    FOREIGN KEY (student_b_id) REFERENCES students(id)
);

-- Mensajes
CREATE TABLE messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL,
    sender_id BIGINT NOT NULL,
    -- Keep the exact LocalDateTime, including legacy sub-microsecond precision.
    timestamp TEXT NOT NULL,
    chat_id INTEGER NOT NULL,
    FOREIGN KEY (sender_id) REFERENCES students(id),
    FOREIGN KEY (chat_id) REFERENCES chats(chat_id)
);

-- Content metadata and canonical follows.
CREATE TABLE content_types (
    content_id INTEGER PRIMARY KEY REFERENCES contents(content_id) ON DELETE CASCADE,
    type TEXT NOT NULL
);

CREATE TABLE follows (
    ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
    follower_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    followed_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    PRIMARY KEY (follower_id, followed_id),
    CHECK (follower_id <> followed_id)
);

CREATE UNIQUE INDEX chats_unordered_students
    ON chats(LEAST(student_a_id, student_b_id), GREATEST(student_a_id, student_b_id));
CREATE INDEX messages_by_chat ON messages(chat_id, message_id);
CREATE INDEX interests_by_student_topic ON students_interests(interest_id, student_id);
CREATE INDEX content_by_topic ON content_topics(interest_id, content_id);
CREATE INDEX help_by_topic ON help_request_topics(interest_id, request_id);
CREATE INDEX followers_by_student ON follows(followed_id, follower_id);
CREATE INDEX content_by_author ON contents(author_id);
CREATE INDEX help_by_student ON help_requests(student_id);

CREATE TABLE bearer_sessions (
    token_hash TEXT NOT NULL PRIMARY KEY CHECK (length(token_hash) = 64),
    user_id TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('STUDENT', 'MODERATOR')),
    expires_at BIGINT NOT NULL
);
CREATE INDEX session_expiry ON bearer_sessions(expires_at);
CREATE INDEX sessions_by_actor ON bearer_sessions(role, user_id);

CREATE TABLE moderator_session_identity (
    singleton INTEGER PRIMARY KEY CHECK (singleton = 1),
    user_id TEXT NOT NULL,
    password_hash TEXT NOT NULL
);

CREATE TABLE content_attachments (
    content_id INTEGER PRIMARY KEY REFERENCES contents(content_id) ON DELETE CASCADE,
    storage_key TEXT NOT NULL UNIQUE,
    file_name TEXT NOT NULL,
    media_type TEXT NOT NULL CHECK (media_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    file_size INTEGER NOT NULL CHECK (file_size BETWEEN 1 AND 5242880)
);

-- Match the existing ASCII-insensitive account email lookup.
CREATE INDEX students_email_ascii ON students(lower(email COLLATE "C"), id);
